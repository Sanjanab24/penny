# --- Isolation ---------------------------------------------------------------------------


def test_recurring_is_private(api: Api, set_today: Callable[[dt.date], None]) -> None:
    item = _create(api, user="user_a", day_of_month=25)

    assert api("get", "/recurring", user="user_b").json()["items"] == []
    for method, body in (("get", None), ("patch", {"active": False}), ("delete", None)):
        res = api(method, f"/recurring/{item['id']}", user="user_b", json=body)
        assert res.status_code == 404, method

    # B's generator never creates A's charges.
    set_today(D(2026, 10, 25))
    assert _generate(api, user="user_b") == 0
    assert _generate(api, user="user_a") == 1
    assert api("get", "/expenses", user="user_b").json()["total"] == 0


