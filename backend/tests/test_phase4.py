@pytest.mark.parametrize(
    ("year", "month", "day", "expected"),
    [
        (2026, 2, 31, D(2026, 2, 28)),
        (2028, 2, 31, D(2028, 2, 29)),
        (2026, 4, 31, D(2026, 4, 30)),
        (2026, 4, 30, D(2026, 4, 30)),
        (2026, 1, 31, D(2026, 1, 31)),
        (2026, 3, 1, D(2026, 3, 1)),
    ],
)
def test_charge_date_clamps_to_short_months(
    year: int, month: int, day: int, expected: dt.date
) -> None:
    assert charge_date(year, month, day) == expected


def test_charge_dates_between_crosses_year_end() -> None:
    assert charge_dates_between(31, D(2026, 11, 1), D(2027, 2, 28)) == [
        D(2026, 11, 30),
        D(2026, 12, 31),
        D(2027, 1, 31),
        D(2027, 2, 28),
    ]
    # Both ends are inclusive.
    assert charge_dates_between(5, D(2026, 10, 5), D(2026, 11, 5)) == [D(2026, 10, 5), D(2026, 11, 5)]
    assert charge_dates_between(5, D(2026, 10, 6), D(2026, 11, 4)) == []


