# --- Generator ---------------------------------------------------------------------------


def test_generator_is_idempotent(api: Api, set_today: Callable[[dt.date], None]) -> None:
    item = _create(api, day_of_month=25)
    assert _generate(api) == 0  # 25 Oct hasn't come yet

    set_today(D(2026, 10, 25))
    assert _generate(api) == 1
    assert _generate(api) == 0
    assert _generate(api) == 0
    charges = _charges(api, item["id"])
    assert [c["date"] for c in charges] == ["2026-10-25"]
    assert charges[0]["category_id"] == _default_id(api, "Subscriptions")


def test_generator_catches_up_missed_months(api: Api, set_today: Callable[[dt.date], None]) -> None:
    item = _create(api, description="Rent", amount="15000", day_of_month=31)
    set_today(D(2027, 3, 1))
    # The app wasn't opened for months: Oct 31, Nov 30, Dec 31, Jan 31, Feb 28.
    assert _generate(api) == 5
    assert [c["date"] for c in _charges(api, item["id"])] == [
        "2026-10-31",
        "2026-11-30",
        "2026-12-31",
        "2027-01-31",
        "2027-02-28",
    ]
    assert _generate(api) == 0


def test_deleted_charge_is_not_recreated(api: Api, set_today: Callable[[dt.date], None]) -> None:
    item = _create(api, day_of_month=19)  # charged today
    charge = _charges(api, item["id"])[0]
    assert api("delete", f"/expenses/{charge['id']}").status_code == 204
    assert _generate(api) == 0
    set_today(D(2026, 10, 30))
    assert _generate(api) == 0
    assert _charges(api, item["id"]) == []


def test_multiple_items(api: Api, set_today: Callable[[dt.date], None]) -> None:
    _create(api, description="Netflix", amount="649", day_of_month=5)
    _create(api, description="Spotify", amount="119", day_of_month=10)
    set_today(D(2026, 11, 10))
    assert _generate(api) == 2


# --- Pause, resume, edit, delete ---------------------------------------------------------


def test_pause_stops_charges_and_resume_skips_paused_months(
    api: Api, set_today: Callable[[dt.date], None]
) -> None:
    item = _create(api, day_of_month=5)
    paused = api("patch", f"/recurring/{item['id']}", json={"active": False}).json()
    assert paused["active"] is False
    assert paused["next_charge_date"] is None

    set_today(D(2026, 12, 20))
    assert _generate(api) == 0

    resumed = api("patch", f"/recurring/{item['id']}", json={"active": True}).json()
    # Nov 5 and Dec 5 were missed while paused and are not backfilled.
    assert resumed["next_charge_date"] == "2027-01-05"
    assert _charges(api, item["id"]) == []

    set_today(D(2027, 1, 5))
    assert _generate(api) == 1
    assert [c["date"] for c in _charges(api, item["id"])] == ["2027-01-05"]


def test_resume_on_billing_day_charges_today(
    api: Api, set_today: Callable[[dt.date], None]
) -> None:
    item = _create(api, day_of_month=10, active=False)
    set_today(D(2026, 11, 10))
    api("patch", f"/recurring/{item['id']}", json={"active": True})
    assert [c["date"] for c in _charges(api, item["id"])] == ["2026-11-10"]


def test_edit_applies_to_future_charges_only(
    api: Api, set_today: Callable[[dt.date], None]
) -> None:
    item = _create(api, day_of_month=19)  # Oct 19 charged at 649
    res = api("patch", f"/recurring/{item['id']}", json={"amount": "199.00", "description": "Netflix Basic"})
    assert res.status_code == 200
    set_today(D(2026, 11, 19))
    _generate(api)
    charges = _charges(api, item["id"])
    assert [(c["date"], c["amount"], c["description"]) for c in charges] == [
        ("2026-10-19", "649.00", "Netflix"),
        ("2026-11-19", "199.00", "Netflix Basic"),
    ]


def test_delete_keeps_generated_expenses(api: Api) -> None:
    item = _create(api, day_of_month=19)
    charge = _charges(api, item["id"])[0]
    assert api("delete", f"/recurring/{item['id']}").status_code == 204
    assert api("get", f"/recurring/{item['id']}").status_code == 404
    kept = api("get", f"/expenses/{charge['id']}").json()
    assert kept["amount"] == "649.00"
    assert kept["recurring_id"] is None


