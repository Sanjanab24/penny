def test_list_orders_active_first_with_monthly_total(api: Api) -> None:
    _create(api, description="Spotify", amount="119", day_of_month=10)
    _create(api, description="Gym", amount="1500", day_of_month=1, active=False)
    _create(api, description="Netflix", amount="649", day_of_month=5)
    page = api("get", "/recurring").json()
    assert [i["description"] for i in page["items"]] == ["Netflix", "Spotify", "Gym"]
    assert page["total"] == 3
    assert page["monthly_total"] == "768.00"


def test_list_pagination(api: Api) -> None:
    for day in range(1, 6):
        _create(api, description=f"Item {day}", day_of_month=day)
    page = api("get", "/recurring?page=2&page_size=2").json()
    assert [i["description"] for i in page["items"]] == ["Item 3", "Item 4"]
    assert page["total"] == 5


def test_budget_counts_recurring_commitments(api: Api) -> None:
    subscriptions, bills = _default_id(api, "Subscriptions"), _default_id(api, "Bills")
    _create(api, description="Netflix", amount="649", day_of_month=5, category_id=subscriptions)
    _create(api, description="Spotify", amount="119", day_of_month=10, category_id=subscriptions)
    _create(api, description="Electricity", amount="1200", day_of_month=15, category_id=bills)
    _create(api, description="Paused", amount="999", day_of_month=1, active=False)

    summary = api("get", "/budgets/2026-10").json()
    assert summary["recurring_total"] == "1968.00"
    by_id = {c["category_id"]: c for c in summary["categories"]}
    assert by_id[subscriptions]["recurring"] == "768.00"
    assert by_id[bills]["recurring"] == "1200.00"

    # Past months show only what happened, not today's commitments.
    assert api("get", "/budgets/2026-09").json()["recurring_total"] == "0.00"
    # Future months are planned with them.
    assert api("get", "/budgets/2026-11").json()["recurring_total"] == "1968.00"


