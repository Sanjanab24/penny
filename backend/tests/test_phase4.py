"""Phase 4: recurring payments and the idempotent monthly generator.

Every API call runs with "today" pinned (conftest.TEST_TODAY = 2026-10-19); `set_today` moves it.
"""

import datetime as dt
from collections.abc import Callable
from typing import Any

import pytest

from app.core.clock import get_today
from app.main import app
from app.services.recurring import charge_date, charge_dates_between
from tests.helpers import Api, _create_category, _default_id

D = dt.date


@pytest.fixture()
def set_today(client: Any) -> Callable[[dt.date], None]:
    # Depends on `client` so its teardown clears this override too.
    def _set(today: dt.date) -> None:
        app.dependency_overrides[get_today] = lambda: today

    return _set


def _create(api: Api, user: str = "user_a", **fields: Any) -> dict[str, Any]:
    body = {"description": "Netflix", "amount": "649.00", "day_of_month": 5, **fields}
    body.setdefault("category_id", _default_id(api, "Subscriptions", user))
    res = api("post", "/recurring", user=user, json=body)
    assert res.status_code == 201, res.json()
    return res.json()


def _generate(api: Api, user: str = "user_a") -> int:
    res = api("post", "/recurring/generate", user=user)
    assert res.status_code == 200, res.json()
    return res.json()["created"]


def _charges(api: Api, item_id: int, user: str = "user_a") -> list[dict[str, Any]]:
    """Expenses generated by one recurring item, oldest first."""
    items = api("get", "/expenses?page_size=200&sort=date_asc", user=user).json()["items"]
    return [e for e in items if e["recurring_id"] == item_id]


